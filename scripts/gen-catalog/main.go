// ---------- Products + Carriers ----------

type prod struct {
	ID, Slug, Class, CarrierDisplay, CarrierSlug, Name string
}

func fieldName(ident, cls string) string {
	prefix := cls + "-"
	stripped := ident
	if strings.HasPrefix(ident, prefix) {
		stripped = ident[len(prefix):]
	}
	return pascal(stripped)
}

func genProductsAndCarriers() {
	sources := []string{"insurance/v2_products.json"}
	var raw map[string][]map[string]any
	if !tryJSON(filepath.Join(insRepo, "v2_products.json"), &raw) {
		preserveOrFail([]string{"products.go", "carriers.go"}, "products")
		return
	}

	classOrder := []string{"fex", "medsup", "preneed", "term"}
	byClass := map[string][]prod{}
	for _, cls := range classOrder {
		byClass[cls] = nil
	}
	for cls, list := range raw {
		for _, p := range list {
			rawID, _ := p["id"].(string)
			ident, _ := p["identifier"].(string)
			name, _ := p["name"].(string)
			car, _ := p["carrier"].(string)
			if rawID == "" {
				fmt.Fprintf(os.Stderr, "ERROR: product %q in class %q has no id — failing loud\n", ident, cls)
				os.Exit(1)
			}
			byClass[cls] = append(byClass[cls], prod{
				ID:             "prod_" + rawID,
				Slug:           ident,
				Class:          cls,
				CarrierDisplay: car,
				CarrierSlug:    slugify(car),
				Name:           name,
			})
		}
	}
	for _, cls := range classOrder {
		sort.Slice(byClass[cls], func(i, j int) bool { return byClass[cls][i].Slug < byClass[cls][j].Slug })
	}

	classPascal := map[string]string{"fex": "Fex", "medsup": "Medsup", "preneed": "Preneed", "term": "Term"}
	total := 0
	for _, cls := range classOrder {
		total += len(byClass[cls])
	}

	var b strings.Builder
	b.WriteString(header(sources))
	b.WriteString(`// Product is a typed catalog entry for one carrier-product combination.
//
// The Id field (prod_<uuid>) is the only stable identity: it is the wire value
// for the v3 prequalify products[] filter, the catalog index key, and the ByID
// lookup key. Name and Carrier are mutable display data — never use them as
// identity. Slugs do not appear on this type.
type Product struct {
	// Id is the opaque product identifier (prod_<uuid>). Stable across carrier
	// renames; the sole wire value the server's products[] filter accepts.
	Id string
	// Name is the human-readable display name. Mutable — do not use as identity.
	Name string
	// Class is the coarse product family wire token (fex, medsup, preneed, term).
	Class string
	// Carrier is the carrier display name.
	Carrier string
}

`)
	// Emit named family types with unexported fields and exported accessor methods.
	// This is the immutability contract: callers use Products.Fex.AetnaAccendo()
	// (a method returning a by-value copy) instead of a mutable exported field.
	for _, cls := range classOrder {
		cp := classPascal[cls]
		typeName := cp + "Products"
		fmt.Fprintf(&b, "// %s is the read-only accessor for the %s product family.\n// Access products via the provided methods; each returns a by-value copy.\ntype %s struct{\n", typeName, strings.ToLower(cls), typeName)
		for _, p := range byClass[cls] {
			fn := fieldName(p.Slug, cls)
			uf := strings.ToLower(fn[:1]) + fn[1:]
			fmt.Fprintf(&b, "\t%s Product\n", uf)
		}
		b.WriteString("}\n\n")
		for _, p := range byClass[cls] {
			fn := fieldName(p.Slug, cls)
			uf := strings.ToLower(fn[:1]) + fn[1:]
			fmt.Fprintf(&b, "// %s returns the Product value for %s.\nfunc (f %s) %s() Product { return f.%s }\n\n", fn, p.Name, typeName, fn, uf)
		}
	}
	b.WriteString(`// productsAccessor is the immutable Products catalog accessor.
// Access family groups as Products.Fex, Products.Medsup, etc.
// Access individual products via family methods: Products.Fex.AetnaAccendo().
// All accessors return by-value copies; the underlying catalog data is immutable.
type productsAccessor struct {
	// Fex is the final expense product family accessor.
	Fex FexProducts
	// Medsup is the Medicare supplement product family accessor.
	Medsup MedsupProducts
	// Preneed is the preneed product family accessor.
	Preneed PreneedProducts
	// Term is the term life product family accessor.
	Term TermProducts
}

// Products is the nested catalog of all known products, grouped by family.
//
// Access individual products as Products.Fex.AetnaAccendo(), etc. Each accessor
// returns a by-value copy; the underlying catalog data cannot be mutated.
// Use ByID to resolve a prod_<uuid> identifier back to its Product value.
var Products = productsAccessor{
`)
	for _, cls := range classOrder {
		cp := classPascal[cls]
		typeName := cp + "Products"
		fmt.Fprintf(&b, "\t%s: %s{\n", cp, typeName)
		for _, p := range byClass[cls] {
			fn := fieldName(p.Slug, cls)
			uf := strings.ToLower(fn[:1]) + fn[1:]
			fmt.Fprintf(&b, "\t\t%s: Product{Id: %q, Name: %q, Class: %q, Carrier: %q},\n",
				uf, p.ID, p.Name, p.Class, p.CarrierDisplay)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")

	// byID is built from literal values (not from Products) so it cannot be desynced by mutations.
	fmt.Fprintf(&b, "// byID is the frozen id→Product reverse-lookup map built at package init.\n// It is built from the same literal data as Products, independent of the Products var.\nvar byID = func() map[string]Product {\n\tm := make(map[string]Product, %d)\n", total)
	for _, cls := range classOrder {
		for _, p := range byClass[cls] {
			fmt.Fprintf(&b, "\tm[%q] = Product{Id: %q, Name: %q, Class: %q, Carrier: %q}\n",
				p.ID, p.ID, p.Name, p.Class, p.CarrierDisplay)
		}
	}
	b.WriteString("\treturn m\n}()\n\n")

	b.WriteString("// ByID returns the Product with the given prod_<uuid> identifier and whether it\n")
	b.WriteString("// was found. It is the only supported catalog lookup: slugs and display names\n")
	b.WriteString("// are not stable identity and are not indexed.\n")
	b.WriteString("func ByID(id string) (Product, bool) {\n\tv, ok := byID[id]\n\treturn v, ok\n}\n\n")

	// productsAll snapshot — built at init from literal values so ProductsAll() is also desync-proof.
	fmt.Fprintf(&b, "// productsAll is the pre-computed by-value snapshot used by ProductsAll.\nvar productsAll = func() []Product {\n\tout := make([]Product, 0, %d)\n", total)
	for _, cls := range classOrder {
		for _, p := range byClass[cls] {
			fmt.Fprintf(&b, "\tout = append(out, Product{Id: %q, Name: %q, Class: %q, Carrier: %q})\n",
				p.ID, p.Name, p.Class, p.CarrierDisplay)
		}
	}
	b.WriteString("\treturn out\n}()\n\n")

	fmt.Fprintf(&b, "// ProductsAll returns every Product in the catalog, in family + alphabetical order.\nfunc ProductsAll() []Product {\n\tout := make([]Product, %d)\n\tcopy(out, productsAll)\n\treturn out\n}\n", total)
	writeFile("products.go", b.String())

	// Carriers
	byCar := map[string]*struct {
		Slug, Disp string
		IDs        []string
	}{}
	for _, cls := range classOrder {
		for _, p := range byClass[cls] {
			c, ok := byCar[p.CarrierSlug]
			if !ok {
				c = &struct {
					Slug, Disp string
					IDs        []string
				}{Slug: p.CarrierSlug, Disp: p.CarrierDisplay}
				byCar[p.CarrierSlug] = c
			}
			c.IDs = append(c.IDs, p.ID)
		}
	}
	carrierSlugs := make([]string, 0, len(byCar))
	for k := range byCar {
		carrierSlugs = append(carrierSlugs, k)
	}
	sort.Strings(carrierSlugs)
	var cv strings.Builder
	cv.WriteString(header(sources))
	cv.WriteString(`// CarrierMetadata describes one carrier. States is empty until upstream
// publishes per-carrier licensure data.
type CarrierMetadata struct {
	Slug, DisplayName string
	// ProductIDs holds the prod_<uuid> identifiers for this carrier's products.
	// Resolve each via ByID to get the full Product value.
	ProductIDs []string
	States     []State
}

`)
	cv.WriteString("var carrierMetadata = map[string]CarrierMetadata{\n")
	for _, s := range carrierSlugs {
		e := byCar[s]
		cv.WriteString(fmt.Sprintf("\t%q: {Slug: %q, DisplayName: %q, ProductIDs: %s},\n",
			e.Slug, e.Slug, e.Disp, quoted(e.IDs)))
	}
	cv.WriteString("}\n\nvar allCarriers = []string{\n")
	for _, s := range carrierSlugs {
		fmt.Fprintf(&cv, "\t%q,\n", s)
	}
	cv.WriteString("}\n\ntype carriersAPI struct{}\n\n// Carriers is the catalog accessor.\nvar Carriers carriersAPI\n\n")
	cv.WriteString("// Values returns every carrier slug, sorted alphabetically.\nfunc (carriersAPI) Values() []string { return append([]string(nil), allCarriers...) }\n\n")
	cv.WriteString("// Metadata returns the carrier metadata and whether slug is known.\nfunc (carriersAPI) Metadata(slug string) (CarrierMetadata, bool) {\n\tm, ok := carrierMetadata[slug]\n\treturn m, ok\n}\n")
	writeFile("carriers.go", cv.String())
}

