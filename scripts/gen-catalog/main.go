// Discovery mirrors the sibling generators (TS/Python/PHP/C#): the platform
// repo is four levels up from this script (packages/go/scripts/gen-catalog ->
// packages/go -> platform root); the engine repo that holds v2_products.json is
// one level above the platform repo. All three are overridable so the generator
// runs identically on a laptop, in the parity harness, and in CI — never bound
// to one developer's absolute paths.
//   SDK_CATALOG_OUT_DIR — where to write the generated catalog package.
//   SDK_PLATFORM_REPO    — isa-platform root (holds shared/schemas, shared/go).
//   SDK_INSURANCE_REPO   — engine repo root (holds v2_*.json).
var (
	outDir   = envOr("SDK_CATALOG_OUT_DIR", filepath.Join(platformRepoDefault(), "packages", "go", "catalog"))
	platRepo = envOr("SDK_PLATFORM_REPO", platformRepoDefault())
	insRepo  = envOr("SDK_INSURANCE_REPO", filepath.Clean(filepath.Join(platformRepoDefault(), "..")))
)

var gaps []string

func envOr(key, fallback string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	return fallback
}

// platformRepoDefault resolves the isa-platform root from this script's own
// source location so the generator is path-independent. Falls back to the
// working directory when the caller location is unavailable.
func platformRepoDefault() string {
	if _, file, _, ok := runtime.Caller(0); ok {
		// file = <platform>/packages/go/scripts/gen-catalog/main.go
		return filepath.Clean(filepath.Join(filepath.Dir(file), "..", "..", "..", ".."))
	}
	if wd, err := os.Getwd(); err == nil {
		return wd
	}
	return "."
}

func main() {
	os.MkdirAll(outDir, 0o755)
	genStates()
	genProductsAndCarriers()
	genMedications()
	genScopesAndErrors()
	genSignEvents()
	genIndex()
	if len(gaps) > 0 {
		fmt.Fprintln(os.Stderr, "gaps:")
		for _, g := range gaps {
			fmt.Fprintln(os.Stderr, "  -", g)
		}
	}
	fmt.Fprintln(os.Stderr, "done")
}

func header(sources []string) string {
	var b strings.Builder
	b.WriteString("// Code " + "generated by scripts/gen-catalog/main.go — do not hand-edit; rerun the generator.\n//\n")
	b.WriteString("// Source data:\n")
	for _, s := range sources {
		b.WriteString("//   - " + s + "\n")
	}
	b.WriteString("\npackage catalog\n\n")
	return b.String()
}

func writeFile(name, content string) {
	p := filepath.Join(outDir, name)
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
		panic(err)
	}
	fmt.Fprintln(os.Stderr, "wrote", p)
}

// preserveOrFail handles a missing product data source without ever shipping an
// empty catalog. v2_products.json lives in the engine repo, which CI runners do
// not check out, so a clean build legitimately misses it. In that case the
// committed catalog is the source of truth — it carries the real prod_<uuid> ids
// and IS the published artifact — so preserve it untouched. Overwriting it with
// an empty stub is the isa-sdk@1.0.1 launch-blocker. With nothing committed to
// preserve, fail loud rather than let an empty catalog reach a registry.
func preserveOrFail(names []string, label string) {
	var missing []string
	for _, n := range names {
		if _, err := os.Stat(filepath.Join(outDir, n)); err != nil {
			missing = append(missing, n)
		}
	}
	if len(missing) > 0 {
		fmt.Fprintf(os.Stderr,
			"FATAL: %s: v2_products.json not found AND no committed catalog to preserve (%s). "+
				"Refusing to emit an empty product catalog. Run where %s exists, or commit a populated catalog first.\n",
			label, strings.Join(missing, ", "), filepath.Join(insRepo, "v2_products.json"))
		os.Exit(1)
	}
	gaps = append(gaps, label+": v2_products.json not found — preserving committed catalog.")
	for _, n := range names {
		fmt.Fprintln(os.Stderr, "preserved committed", filepath.Join(outDir, n))
	}
}

func pascal(s string) string {
	re := regexp.MustCompile(`[^a-zA-Z0-9]+`)
	parts := re.Split(s, -1)
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]))
		if len(p) > 1 {
			b.WriteString(strings.ToLower(p[1:]))
		}
	}
	id := b.String()
	if id != "" && id[0] >= '0' && id[0] <= '9' {
		id = "X" + id
	}
	return id
}

func slugify(s string) string {
	out := strings.ToLower(s)
	out = regexp.MustCompile(`[^a-z0-9]+`).ReplaceAllString(out, "-")
	return strings.Trim(out, "-")
}

func tryJSON(p string, dst any) bool {
	f, err := os.ReadFile(p)
	if err != nil {
		return false
	}
	if err := json.Unmarshal(f, dst); err != nil {
		fmt.Fprintln(os.Stderr, "parse", p, err)
		return false
	}
	return true
}

func tryText(p string) (string, bool) {
	f, err := os.ReadFile(p)
	if err != nil {
		return "", false
	}
	return string(f), true
}

func quoted(in []string) string {
	if len(in) == 0 {
		return "nil"
	}
	parts := make([]string, len(in))
	for i, s := range in {
		parts[i] = fmt.Sprintf("%q", s)
	}
	return "[]string{" + strings.Join(parts, ", ") + "}"
}

func productSlice(in []string) string {
	if len(in) == 0 {
		return "nil"
	}
	parts := make([]string, len(in))
	for i, s := range in {
		parts[i] = fmt.Sprintf("%q", s)
	}
	return "[]Product{" + strings.Join(parts, ", ") + "}"
}

